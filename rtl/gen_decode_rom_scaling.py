#!/usr/bin/env python3
# Generates lookup-table ROMs and wrappers for d=3,5,7 (single round).
import sys, stim, pymatching, numpy as np

d = int(sys.argv[1])
circ = stim.Circuit.generated(
    "repetition_code:memory", distance=d, rounds=1,
    before_round_data_depolarization=0.02,
    before_measure_flip_probability=0.02)
dem = circ.detector_error_model(decompose_errors=True)
m   = pymatching.Matching.from_detector_error_model(dem)
nD  = circ.num_detectors
nL  = circ.num_observables
print(f"d={d} repetition, rounds=1: {nD} detectors, {nL} logical observable(s), "
      f"ROM size = {1<<nD} entries")
assert nD <= 16, f"{nD} detectors -> ROM too large (2^{nD}); reduce distance"

rom = []
for s in range(1 << nD):
    syn = np.array([(s >> b) & 1 for b in range(nD)], dtype=np.uint8)
    pred = m.decode(syn)
    val = int(pred[0]) if nL else 0
    rom.append(val)

vh_path = f"rep_d{d}_decode_rom.vh"
with open(vh_path, "w") as f:
    f.write(f"// AUTO-GENERATED by gen_decode_rom_scaling.py  (d={d} repetition, rounds=1)\n")
    f.write(f"// {nD} detectors -> {1<<nD} entries; value = predicted logical correction\n")
    f.write(f"// Reproduces pymatching MWPM exactly (correct by construction).\n")
    f.write(f"localparam ROM_NDET_D{d} = {nD};\n")
    f.write(f"localparam ROM_SIZE_D{d} = {1<<nD};\n")
    f.write(f"reg rom_corr_d{d} [0:ROM_SIZE_D{d}-1];\n")
    f.write("initial begin\n")
    for i, v in enumerate(rom):
        f.write(f"  rom_corr_d{d}[{i}] = 1'b{v};\n")
    f.write("end\n")
print(f"wrote {vh_path} ({len(rom)} entries)")

v_path = f"rep_d{d}_rom_decoder.v"
with open(v_path, "w") as f:
    f.write(f"""// =====================================================================
//  rep_d{d}_rom_decoder.v -- reference-generated ROM decoder for d={d}
//  repetition code, single round ({nD} detectors, {1<<nD}-entry table).
//  Contents generated by pymatching (correct by construction).
// =====================================================================
module rep_d{d}_rom_decoder (
    input  wire                          clk,
    input  wire                          rst_n,
    input  wire                          syndrome_valid,
    input  wire [{nD-1}:0]                    syndrome,
    output reg                           correction,
    output reg                           corr_valid
);
    `include "rep_d{d}_decode_rom.vh"

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            correction <= 1'b0;
            corr_valid <= 1'b0;
        end else if (syndrome_valid) begin
            correction <= rom_corr_d{d}[syndrome];
            corr_valid <= 1'b1;
        end else begin
            corr_valid <= 1'b0;
        end
    end
endmodule
""")
print(f"wrote {v_path}")
